"""Write rtl/synth_board/synth_top.sv: hornet_board with every input driven from an LFSR and
every output folded into one pin, for a standalone area and Fmax compile of the board
(rtl/synth_board). Run it again when the board's ports change."""
import re
from pathlib import Path

REPO = Path(__file__).resolve().parent.parent
src = (REPO / "rtl/board/hornet_board.sv").read_text()
body = re.search(r"module hornet_board (?:#\(.*?\n\) )?\((.*?)\n\);", src, re.S).group(1)

ins, outs = [], []
for line in body.splitlines():
    line = line.split("//")[0].strip().rstrip(",")
    m = re.match(r"(input|output)\s+logic\s*(\[(\d+):0\])?\s*(.*)", line)
    if not m:
        continue
    width = int(m.group(3)) + 1 if m.group(3) else 1
    for name in (n.strip() for n in m.group(4).split(",")):
        if name in ("clk", "reset"):
            continue
        (ins if m.group(1) == "input" else outs).append((name, width))

lines = ["// generated by scripts/synth_board_top.py from rtl/board/hornet_board.sv",
         "module synth_top (input logic clk, input logic reset, input logic din, output logic dout);",
         "    logic [255:0] lfsr;",
         "    always_ff @(posedge clk) lfsr <= {lfsr[254:0], din ^ lfsr[255] ^ lfsr[253] ^ lfsr[250] ^ lfsr[245]};"]
off = 0
for name, w in ins:
    lines.append(f"    logic [{w - 1}:0] {name};")
for name, w in outs:
    lines.append(f"    logic [{w - 1}:0] {name};")
for name, w in ins:
    # debug and load ports held idle, as in the core: the board runs, nothing is loaded or read
    if name.startswith(("ppc_dbg_", "dsp_dbg_", "ld_")):
        lines.append(f"    assign {name} = '0;")
    elif name == "run":
        lines.append(f"    assign {name} = 1'b1;")
    elif name == "line_clocks":
        lines.append(f"    assign {name} = 16'd2560;")
    else:
        bits = [f"lfsr[{(off + k) % 256}]" for k in range(w)]
        off += w
        lines.append(f"    assign {name} = {{{', '.join(reversed(bits))}}};")
lines.append('    hornet_board #(.RECIP_HEX("../raster/vraster_recip.hex")) board (.*);')
lines.append("    always_ff @(posedge clk) dout <= ^{" + ", ".join(n for n, _ in outs) + "};")
lines.append("endmodule")
out = REPO / "rtl/synth_board/synth_top.sv"
out.parent.mkdir(exist_ok=True)
out.write_text("\n".join(lines) + "\n")
print(f"{len(ins)} inputs, {len(outs)} outputs -> {out}")
